// a still, generated rather than rendered.
//
// the persona has never met the model, so the frame is held together by text:
// the four consistencies from the head, a seed derived from them, and a rule
// about what a series may vary. a shoot can move the camera; it cannot move
// the person, the room or how close we are.

import {
  consistencyBlocks,
  consistencyDrift,
  consistencyProblems,
  consistencyPrompt,
  consistencySeed,
  type ConsistencyAxis,
  type ConsistencyBlocks,
  type SceneSpec,
} from "../persona/consistency.ts";
import type { PersonaManifest } from "../persona/schema.ts";
import { frameFor, textBand, type Frame } from "./frames.ts";

// what a series is allowed to change between frames. composition is the
// director's variable; the other three are the film.
export const SERIES_LOCKED: ConsistencyAxis[] = ["character", "location", "magnification"];

export interface StillRequest {
  scene: SceneSpec;
  frameTarget: string;
  // the first frame of the series, when this still belongs to one
  reference?: ConsistencyBlocks;
}

export interface StillPlan {
  frameTarget: string;
  frame: Frame;
  band: { top: number; bottom: number };
  blocks: ConsistencyBlocks;
  prompt: string;
  seed: number;
  drifted: ConsistencyAxis[];
}

export function planStill(persona: PersonaManifest, req: StillRequest): StillPlan {
  const frame = frameFor(req.frameTarget);
  const blocks = consistencyBlocks(persona, req.scene);
  const problems = consistencyProblems(blocks);
  if (problems.length) {
    throw new Error(`still: ${problems.map((p) => `${p.axis}: ${p.problem}`).join("; ")}`);
  }
  return {
    frameTarget: req.frameTarget,
    frame,
    band: textBand(frame),
    blocks,
    prompt: consistencyPrompt(persona, req.scene),
    seed: consistencySeed(blocks),
    drifted: req.reference ? lockedDrift(req.reference, blocks) : [],
  };
}

export function lockedDrift(reference: ConsistencyBlocks, candidate: ConsistencyBlocks): ConsistencyAxis[] {
  return consistencyDrift(reference, candidate).filter((axis) => SERIES_LOCKED.includes(axis));
}

// the provider seam. a still is generated by whatever model is configured;
// this branch never claims to own the model.
export interface StillProvider {
  name: string;
  generate(input: { prompt: string; seed: number; frame: Frame }): Promise<{ uri: string }>;
}

export interface StillReceipt {
  provider: string;
  uri: string;
  seed: number;
  prompt: string;
  frame: Frame;
  drifted: ConsistencyAxis[];
}

export async function generateStill(provider: StillProvider, plan: StillPlan): Promise<StillReceipt> {
  if (plan.drifted.length) {
    // the honest failure: the model would produce a different film, and the
    // receipt would lie about it being the same series.
    throw new Error(`still: series drift in ${plan.drifted.join(", ")}`);
  }
  const out = await provider.generate({ prompt: plan.prompt, seed: plan.seed, frame: plan.frame });
  return { provider: provider.name, uri: out.uri, seed: plan.seed, prompt: plan.prompt, frame: plan.frame, drifted: plan.drifted };
}
